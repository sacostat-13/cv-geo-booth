#!/usr/bin/env python3
"""Bake the QR code for the booth screen.

    pip install segno
    python3 make-qr.py https://your-booth-url/

Writes qr.js next to this file. display.html picks it up automatically.
Re-run it whenever the phone URL changes.
"""
import base64
import io
import re
import sys
import pathlib

try:
    import segno
except ImportError:
    sys.exit("pip install segno first")

HERE = pathlib.Path(__file__).parent


def url_from_config():
    cfg = (HERE / "config.js").read_text(encoding="utf-8")
    m = re.search(r"phoneUrl:\s*'([^']+)'", cfg)
    return m.group(1) if m else None


def main():
    url = sys.argv[1] if len(sys.argv) > 1 else url_from_config()
    if not url or "example.org" in url:
        sys.exit("Pass the booth URL, or set phoneUrl in config.js first.")

    qr = segno.make(url, error="h")
    buf = io.BytesIO()
    qr.save(buf, kind="png", scale=12, border=2, dark="#120F1C", light="#FFFFFF")
    data = base64.b64encode(buf.getvalue()).decode("ascii")

    (HERE / "qr.js").write_text(
        "/* generated by make-qr.py for %s */\n" % url
        + 'window.BOOTH_QR = "data:image/png;base64,%s";\n' % data,
        encoding="utf-8",
    )
    print("wrote qr.js for", url, "(%.1f KB)" % (len(data) / 1024))
    print('Add <script src="qr.js"></script> to display.html before display.js if it is not there yet.')


if __name__ == "__main__":
    main()
